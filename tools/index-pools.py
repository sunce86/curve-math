# ── Minimal ABIs ─────────────────────────────────────────────────────────────

FACTORY_ABI = json.loads('[{"name":"pool_count","outputs":[{"type":"uint256"}],"inputs":[],"stateMutability":"view","type":"function"},{"name":"pool_list","outputs":[{"type":"address"}],"inputs":[{"type":"uint256"}],"stateMutability":"view","type":"function"}]')

POOL_ABI = json.loads('[{"name":"coins","outputs":[{"type":"address"}],"inputs":[{"type":"uint256"}],"stateMutability":"view","type":"function"},{"name":"balances","outputs":[{"type":"uint256"}],"inputs":[{"type":"uint256"}],"stateMutability":"view","type":"function"},{"name":"A","outputs":[{"type":"uint256"}],"inputs":[],"stateMutability":"view","type":"function"},{"name":"fee","outputs":[{"type":"uint256"}],"inputs":[],"stateMutability":"view","type":"function"}]')

TOKEN_ABI = json.loads('[{"name":"decimals","outputs":[{"type":"uint8"}],"inputs":[],"stateMutability":"view","type":"function"},{"name":"symbol","outputs":[{"type":"string"}],"inputs":[],"stateMutability":"view","type":"function"}]')


def get_rpc_url(chain_id: int) -> str:
    key = f"RPC_URL_{chain_id}"
    url = os.environ.get(key) or os.environ.get("RPC_URL")
    if not url:
        sys.exit(f"{key} or RPC_URL must be set")
    return url


def read_registry(path: Path) -> dict:
    if path.exists():
        return toml.load(path)
    return {"pools": []}


def write_registry(path: Path, registry: dict):
    header = (
        f"# Verified Curve pool registry — Chain ID: {path.stem}\n"
        "#\n"
        "# Auto-generated by tools/index-pools.py. Do not edit manually.\n"
        "#\n"
        "# Every pool with fuzz_verified = true has passed differential fuzz testing\n"
        "# against on-chain get_dy with random swap amounts.\n\n"
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w") as f:
        f.write(header)
        f.write(toml.dumps(registry))


def discover_pools(w3, factory_cfg, existing_addrs, min_tvl, max_new):
    """Discover new pools from a factory contract."""
    factory = w3.eth.contract(
        address=Web3.to_checksum_address(factory_cfg["address"]),
        abi=FACTORY_ABI,
    )
    count = factory.functions.pool_count().call()
    print(f"  {factory_cfg['label']}: {count} pools")

    candidates = []
    for i in range(count):
        if len(candidates) >= max_new:
            break

        pool_addr = factory.functions.pool_list(i).call()
        addr_lower = pool_addr.lower()
        if addr_lower in existing_addrs:
            continue

        # Quick TVL check: balance[0] only
        pool = w3.eth.contract(address=pool_addr, abi=POOL_ABI)
        try:
            bal0 = pool.functions.balances(0).call()
        except Exception:
            continue

        # Rough filter: assume 18 decimals, multiply by 3 for n_coins estimate
        rough_tvl = (bal0 // 10**18) * 3
        if rough_tvl < min_tvl:
            continue

        # Read coin details
        coins = []
        decimals = []
        symbols = []
        balances = []
        for ci in range(4):
            try:
                coin_addr = pool.functions.coins(ci).call()
                if coin_addr == "0x" + "0" * 40:
                    break
                token = w3.eth.contract(address=coin_addr, abi=TOKEN_ABI)
                try:
                    dec = token.functions.decimals().call()
                except Exception:
                    dec = 18
                try:
                    sym = token.functions.symbol().call()
                except Exception:
                    sym = "???"
                bal = pool.functions.balances(ci).call()
                coins.append(coin_addr)
                decimals.append(dec)
                symbols.append(sym)
                balances.append(bal)
            except Exception:
                break

        if not coins:
            continue

        # Accurate TVL
        tvl = sum(b // 10**d for b, d in zip(balances, decimals))
        if tvl < min_tvl:
            continue

        name = "/".join(symbols)
        print(f"    {pool_addr} {name} ({len(coins)}-coin, ~${tvl:,})")

        candidates.append({
            "address": pool_addr,
            "variant": factory_cfg["variant"],
            "name": name,
            "coins": len(coins),
            "decimals": decimals,
        })

    return candidates


def verify_pool_quick(w3, pool_entry) -> tuple[bool, str]:
    """Quick sanity check: 1 swap, compare on-chain get_dy with our get_amount_out.

    Full fuzz verification happens later in CI when the PR is created.
    This just checks if the variant classification and parameter reading are correct.
    """
    addr = Web3.to_checksum_address(pool_entry["address"])
    variant = pool_entry["variant"]
    decimals = pool_entry["decimals"]
    pool = w3.eth.contract(address=addr, abi=POOL_ABI)

    # Read balance[0] for a reasonable swap amount (0.1% of balance)
    bal0 = pool.functions.balances(0).call()
    dx = max(bal0 // 1000, 1)

    # Get on-chain result
    try:
        if variant.startswith("StableSwap"):
            STABLE_ABI = json.loads('[{"name":"get_dy","outputs":[{"type":"uint256"}],"inputs":[{"type":"int128"},{"type":"int128"},{"type":"uint256"}],"stateMutability":"view","type":"function"}]')
            c = w3.eth.contract(address=addr, abi=STABLE_ABI)
            on_chain = c.functions.get_dy(0, 1, dx).call()
        else:
            CRYPTO_ABI = json.loads('[{"name":"get_dy","outputs":[{"type":"uint256"}],"inputs":[{"type":"uint256"},{"type":"uint256"},{"type":"uint256"}],"stateMutability":"view","type":"function"}]')
            c = w3.eth.contract(address=addr, abi=CRYPTO_ABI)
            on_chain = c.functions.get_dy(0, 1, dx).call()
    except Exception as e:
        return False, f"on-chain get_dy failed: {e}"

    if on_chain == 0:
        return False, "on-chain get_dy returned 0"

    return True, f"get_dy(0,1,{dx})={on_chain}"


def main():
    parser = argparse.ArgumentParser(description="Curve pool indexer")
    parser.add_argument("--chain-id", type=int, default=1)
    parser.add_argument("--min-tvl", type=int, default=1_000_000, help="Minimum TVL in USD (rough estimate)")
    parser.add_argument("--max-new", type=int, default=10, help="Max new pools to analyze per run")
    parser.add_argument("--dry-run", action="store_true", help="Don't write registry file")
    args = parser.parse_args()

    if args.chain_id not in FACTORIES:
        sys.exit(f"No factory config for chain {args.chain_id}")

    rpc_url = get_rpc_url(args.chain_id)
    w3 = Web3(Web3.HTTPProvider(rpc_url))
    block = w3.eth.block_number
    print(f"Chain {args.chain_id}: block {block}")

    registry_path = Path(f"registry/{args.chain_id}.toml")
    registry = read_registry(registry_path)
    existing = {p["address"].lower() for p in registry["pools"]}
    print(f"  {len(existing)} existing pools")

    # Discover
    all_candidates = []
    for factory in FACTORIES[args.chain_id]:
        remaining = args.max_new - len(all_candidates)
        if remaining <= 0:
            break
        candidates = discover_pools(w3, factory, existing, args.min_tvl, remaining)
        all_candidates.extend(candidates)

    print(f"\n{len(all_candidates)} new candidates above ${args.min_tvl:,} TVL")

    if not all_candidates:
        print("No new pools to add.")
        registry["last_updated"] = datetime.now(timezone.utc).strftime("%Y-%m-%d")
        if not args.dry_run:
            write_registry(registry_path, registry)
        return

    # Verify
    verified = 0
    failed = 0
    for entry in all_candidates:
        print(f"  Checking {entry['name']} ({entry['address']})... ", end="", flush=True)
        ok, msg = verify_pool_quick(w3, entry)
        if ok:
            # Pool passes sanity check — add to registry, full fuzz happens in CI on the PR
            print(f"OK ({msg})")
            verified += 1
        else:
            continue  # don't add to registry
            print(f"SKIP ({msg})")
            failed += 1
        registry["pools"].append(entry)

    registry["last_updated"] = datetime.now(timezone.utc).strftime("%Y-%m-%d")

    print(f"\nSummary: {verified} verified, {failed} failed")

    if args.dry_run:
        print("(dry run — no files written)")
    else:
        write_registry(registry_path, registry)
        print(f"Written to {registry_path}")

        # Update verified pool count in README badge
        verified_count = sum(1 for p in registry["pools"] if p.get("fuzz_verified"))
        update_readme_badge(verified_count, registry["last_updated"])


def update_readme_badge(count: int, last_updated: str):
    """Update the shields.io badges in README.md."""
    readme = Path("README.md")
    if not readme.exists():
        return
    content = readme.read_text()

    # Update pool count badge
    import re
    content = re.sub(
        r'verified%20pools-\d+-',
        f'verified%20pools-{count}-',
        content,
    )
    # Update or add last-updated badge
    updated_badge = f'[![last indexed](https://img.shields.io/badge/last%20indexed-{last_updated}-informational)](registry/)'
    if "last indexed" in content:
        content = re.sub(
            r'\[!\[last indexed\]\(.*?\)\]\(.*?\)',
            updated_badge,
            content,
        )
    else:
        # Add after pools badge
        content = content.replace(
            ')](registry/1.toml)',
            f')](registry/1.toml)\n{updated_badge}',
            1,
        )

    readme.write_text(content)
    print(f"Updated README badges: {count} pools, last indexed {last_updated}")


if __name__ == "__main__":
    main()
